# Question:
# Write a Python program that uses a for loop and range()
# to print the first 10 multiples of 5.


# ------------------------------------------------------------
# Solution
# ------------------------------------------------------------

for number in range(5, 51, 5):
    print(number)


# ------------------------------------------------------------
# Expected Output
# ------------------------------------------------------------

# 5
# 10
# 15
# 20
# 25
# 30
# 35
# 40
# 45
# 50


# ------------------------------------------------------------
# Explanation
# ------------------------------------------------------------

# range(5, 51, 5)
#
# 5  -> Starting number
# 51 -> Stop value (not included)
# 5  -> Step size
#
# The loop increases the number by 5 each time.
#
# 5 -> 10 -> 15 -> 20 -> ... -> 50