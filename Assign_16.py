# Create a tuple
numbers = (10, 20, 30, 20, 40, 50, 20)

# Print the complete tuple
print("Tuple:", numbers)

# Print the data type
print("Data Type:", type(numbers))

# Count how many times 20 appears
print("Total occurrences of 20:", numbers.count(20))

# Print the first occurrence (index) of 20
print("First occurrence of 20 is at index:", numbers.index(20))